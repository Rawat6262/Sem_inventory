"use client";

// Quotations module: standalone quote documents (not linked to any Client or
// Exhibition record) with line items, auto-computed subtotal/GST/total, and
// a browser print/export-as-PDF flow (no PDF generation on the backend).
// Every call goes through the /api/backend proxy.

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { api } from "@/lib/api";

export type QuotationItem = { _id: string; title: string; size?: string; description: string[]; cost: number };

export type Quotation = {
  _id: string;
  title: string;
  date: string;
  exhibition_name: string;
  exhibition_date: string; // free text, often a range like "22-24 July 2026"
  company_name: string;
  venue?: string;
  gst_no?: string;
  items: QuotationItem[];
  subtotal: number;
  gst_percent: number;
  gst_amount: number;
  total: number;
  createdAt: string;
};

const numberFormat = new Intl.NumberFormat("en-IN");
export const fmt = (n: number | null | undefined) => numberFormat.format(n ?? 0);

const moneyFormat = new Intl.NumberFormat("en-IN", { style: "currency", currency: "INR", maximumFractionDigits: 0 });
export const fmtMoney = (n: number | null | undefined) => moneyFormat.format(n ?? 0);

const dateFormat = new Intl.DateTimeFormat("en-IN", { day: "numeric", month: "short", year: "numeric" });
export const fmtDate = (d: string | null | undefined) => (d ? dateFormat.format(new Date(d)) : "—");

export const quotationKeys = {
  all: ["quotations"] as const,
  list: ["quotations", "list"] as const,
  detail: (id: string) => ["quotations", "detail", id] as const,
};

export function useQuotations() {
  return useQuery({
    queryKey: quotationKeys.list,
    queryFn: async () => (await api<{ data: Quotation[] }>("getallquotations")).data,
  });
}

export function useQuotation(id: string) {
  return useQuery({
    queryKey: quotationKeys.detail(id),
    queryFn: async () => (await api<{ data: Quotation }>(`getquotationbyid/${id}`)).data,
    enabled: Boolean(id),
  });
}

export function useSearchQuotations() {
  return useMutation({
    mutationFn: (keyword: string) => api<{ total: number; data: Quotation[] }>("searchquotation", { method: "POST", body: { keyword } }),
  });
}

export function useQuotationsMutation<TInput>(fn: (input: TInput) => Promise<unknown>) {
  const qc = useQueryClient();
  return useMutation({
    mutationFn: fn,
    onSuccess: () => qc.invalidateQueries({ queryKey: quotationKeys.all }),
  });
}

// title is auto-generated by the backend (company name + a running count).
export type QuotationHeaderInput = {
  exhibition_name: string;
  exhibition_date: string;
  company_name: string;
  venue?: string;
  gst_percent?: number;
  date?: string;
};
export const createQuotation = (body: QuotationHeaderInput) => api<{ data: Quotation }>("createquotation", { method: "POST", body });

export const updateQuotation = ({ id, ...body }: Partial<QuotationHeaderInput> & { id: string; title?: string }) =>
  api(`updatequotation/${id}`, { method: "PUT", body });

export const deleteQuotation = (id: string) => api(`deletequotation/${id}`, { method: "DELETE" });

export type QuotationItemInput = { title: string; size?: string; description: string[]; cost: number };

export const addQuotationItem = ({ id, ...body }: QuotationItemInput & { id: string }) =>
  api(`quotation/${id}/items`, { method: "POST", body });

export const updateQuotationItem = ({ id, itemId, ...body }: Partial<QuotationItemInput> & { id: string; itemId: string }) =>
  api(`quotation/${id}/items/${itemId}`, { method: "PATCH", body });

export const removeQuotationItem = ({ id, itemId }: { id: string; itemId: string }) =>
  api(`quotation/${id}/items/${itemId}`, { method: "DELETE" });
